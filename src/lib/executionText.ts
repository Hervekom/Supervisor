export const execText = (lang: Lang): ExecMessages => (lang === 'fr' ? fr : en);

/** Text and recovery step for a reason code such as "rows_differ:8760" or "also_err_file". */
export function reasonText(code: string, lang: Lang): { text: string; next: string } {
  const m = execText(lang);
  const c = code.replace(/^also_/, '');
  const i = c.indexOf(':');
  const key = i < 0 ? c : c.slice(0, i);
  const v = i < 0 ? '' : c.slice(i + 1);
  const [text, next] = m.reasons[key] ?? m.reasons.unknown;
  const f = (s: string) => s.replace(/\{v\}/g, v);
  return { text: f(text), next: f(next) };
}
